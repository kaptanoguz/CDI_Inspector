#!/usr/bin/env python3
"""
CDI Section 5 (Chemical / Product) from the summary Excel → js/cdi/sec5.js

The type-specific CDI booklets (5C Chemical, 5P Product) are not available, so
Section 5 is taken from a summary workbook made from them:
  tools/source/cdi/CDI_SIR_10th_Edition_Full_Questionnaire.xlsx
    sheets 01_Documentation and 02_Cargo: Ref · Inspection Question · Cat · Gp,
    with a cell comment holding a short guidance note.

Statements in the workbook are shortened and are NOT the booklet text, so every
entry is marked x: 1 and the app labels it as a summary. Only rows with a full
question number are taken ("5.2.1 / 5.9.1" → 5.2.1, product number kept in alt);
rows such as "5.5.x" are skipped. A product-only number (5.8–5.13) is used when
there is no chemical one. When the 5C/5P booklets become available, import them
with tools/import_cdi.py instead and delete this file's output.

Usage:  python3 tools/import_cdi_xlsx.py   (needs openpyxl)
"""
import datetime
import json
import pathlib
import re

import openpyxl

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools/source/cdi/CDI_SIR_10th_Edition_Full_Questionnaire.xlsx"
OUT = ROOT / "js/cdi/sec5.js"
SHEETS = ["01_Documentation", "02_Cargo"]
NUM = re.compile(r"^5\.\d+\.\d+(?:-\d+)?$")


def main():
    wb = openpyxl.load_workbook(SRC)
    out, skipped = {}, []
    for name in SHEETS:
        for row in wb[name].iter_rows(min_row=4):
            ref, q, cat, gp = (row[i].value for i in range(4))
            if not ref or not q or not str(ref).startswith("5."):
                continue
            nums = [s.strip() for s in str(ref).split("/") if NUM.match(s.strip())]
            if not nums:
                skipped.append(str(ref))
                continue
            no = nums[0].split("-")[0]
            if no in out:
                continue
            note = next((c.comment.text.strip() for c in row[:2] if c.comment), "")
            e = {"q": str(q).strip(), "cat": (cat or "").strip(), "gp": (gp or "").strip(), "x": 1}
            if nums[0] != no:
                e["range"] = nums[0]
            if len(nums) > 1:
                e["alt"] = " / ".join(nums[1:])
            if note:
                e["g"] = [["Excel note", "", note]]
            out[no] = e

    key = lambda k: [int(p) for p in k.split(".")]
    out = {k: out[k] for k in sorted(out, key=key)}
    js = ("/* Generated by tools/import_cdi_xlsx.py — do not edit by hand.\n"
          "   CDI Section 5 (Chemical / Product) from a summary workbook, not the booklets:\n"
          "   shortened statements (x: 1), alt: the matching Product (5P) number. */\n"
          f"CDI_META.sec5 = {json.dumps({'generated': str(datetime.date.today()), 'source': SRC.name, 'questions': len(out)})};\n"
          "Object.assign(CDI_CORE, {\n"
          + ",\n".join(f"{json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in out.items())
          + "\n});\n")
    OUT.write_text(js, encoding="utf-8")
    print(f"{len(out)} questions → {OUT.relative_to(ROOT)}; skipped (no full number): {len(skipped)}")


if __name__ == "__main__":
    main()
